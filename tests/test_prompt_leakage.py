"""tests/test_prompt_leakage.py
Test that prompts generated by harness/prompt.py contain no leakage:
- Public unit tests from tasks/*/public_tests/ are visible and allowed.
- No hidden seeds from graders/hidden_seeds.py.
- No Tier 2 trace content from tasks/*/tier2_trace.json.
- No difficulty_reason from tasks/*/task.toml.
- No reference implementation code from reference/.
- No mutant code from mutants/.
"""
import ast
import json
from pathlib import Path
from typing import Any

import pytest

try:
    import tomllib as tomli
except ImportError:
    import tomli  # type: ignore

from graders.hidden_seeds import get_task_seeds
from harness.prompt import build_prompt_for_task

REPO_ROOT = Path(__file__).resolve().parent.parent
TASKS = [
    "f1_fee_a",
    "f1_fee_b",
    "f2_replace_a",
    "f2_replace_b",
    "f3_fix_a",
    "f3_fix_b",
    "f4_waterfall_b",
    "f5_basket_b",
]


def _extract_executable_lines(py_code: str) -> list[str]:
    """Extract non-trivial executable code lines from python source."""
    tree = ast.parse(py_code)
    lines: list[str] = []
    for node in ast.walk(tree):
        if isinstance(node, (ast.Assign, ast.AugAssign, ast.If, ast.While, ast.For, ast.Return)):
            src_line = py_code.splitlines()[node.lineno - 1].strip()
            if (
                src_line
                and not src_line.startswith("raise NotImplementedError")
                and not src_line.startswith("return [")
                and not src_line.startswith("return None")
                and not src_line.startswith("return 0")
                and len(src_line) > 15
            ):
                lines.append(src_line)
    return lines


@pytest.mark.parametrize("task_id", TASKS)
def test_prompt_contains_no_leaks(task_id: str):
    prompt_obj = build_prompt_for_task(task_id)
    full_prompt = f"{prompt_obj.system}\n\n{prompt_obj.user_prompt}"

    task_dir = REPO_ROOT / "tasks" / task_id
    task_toml = task_dir / "task.toml"
    meta: dict[str, Any] = tomli.loads(task_toml.read_text(encoding="utf-8"))

    # 1. No difficulty_reason
    difficulty_reason = meta.get("difficulty_reason", "")
    if difficulty_reason and len(difficulty_reason.strip()) > 3:
        assert difficulty_reason not in full_prompt, (
            f"Prompt for {task_id} leaked difficulty_reason: {difficulty_reason}"
        )

    # 2. No hidden seeds
    hidden_seeds = get_task_seeds(task_id, 20)
    for s in hidden_seeds:
        assert f"seed={s}" not in full_prompt
        assert f"seed: {s}" not in full_prompt
        assert f"seed {s}" not in full_prompt

    # 3. No tier2_trace content
    tier2_file = task_dir / "tier2_trace.json"
    if tier2_file.exists():
        t2_data = json.loads(tier2_file.read_text(encoding="utf-8"))
        assert "tier2_trace.json" not in full_prompt
        assert "checkpoint_index" not in full_prompt
        assert "expected_reports" not in full_prompt
        assert "expected_book" not in full_prompt
        for chk in t2_data.get("checkpoints", []):
            if "expected_reports" in chk and chk["expected_reports"]:
                chk_str = json.dumps(chk["expected_reports"])
                assert chk_str not in full_prompt

    # 4. No reference implementation logic in target stub section
    # The Target Files section in the prompt must only provide stubs, never reference implementation
    stub_section = ""
    if "## Target Files to Implement" in full_prompt:
        stub_part = full_prompt.split("## Target Files to Implement", 1)[1]
        stub_section = stub_part.split("## Reference Context", 1)[0]

    ref_dir = REPO_ROOT / "reference" / task_id
    if ref_dir.exists():
        for ref_file in ref_dir.glob("*.py"):
            ref_code = ref_file.read_text(encoding="utf-8")
            exec_lines = _extract_executable_lines(ref_code)
            for line in exec_lines:
                assert line not in stub_section, (
                    f"Prompt stub section for {task_id} leaked reference code line: {line}"
                )

    # 5. No mutant code or mutant names
    mutants_dir = REPO_ROOT / "mutants" / task_id
    if mutants_dir.exists():
        for m_dir in mutants_dir.iterdir():
            if m_dir.is_dir():
                assert m_dir.name not in full_prompt, (
                    f"Prompt for {task_id} leaked mutant name: {m_dir.name}"
                )
                for m_file in m_dir.glob("*.py"):
                    m_lines = _extract_executable_lines(m_file.read_text(encoding="utf-8"))
                    for m_line in m_lines:
                        if "MUTANT" in m_line:
                            assert m_line not in full_prompt


@pytest.mark.parametrize("task_id", TASKS)
def test_prompt_contains_public_tests(task_id: str):
    """Verify that public unit tests are included in the prompt for visibility."""
    prompt_obj = build_prompt_for_task(task_id)
    full_prompt = f"{prompt_obj.system}\n\n{prompt_obj.user_prompt}"
    assert "## Public Tests (Visible)" in full_prompt
    assert f"test_{task_id}" in full_prompt


def test_leak_detector_fails_on_artificial_leak():
    """Verify that the leakage check correctly fails if reference code is leaked."""
    fake_prompt = "## Target Files to Implement\nreturn fee_below + fee_above\n## Reference Context"
    stub_part = fake_prompt.split("## Target Files to Implement")[1]
    stub_section = stub_part.split("## Reference Context")[0]
    with pytest.raises(AssertionError):
        assert "return fee_below + fee_above" not in stub_section
