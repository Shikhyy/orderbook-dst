"""tools/mutant_tier_analysis.py
Which grading tier catches each hand-written bug?

Runs every mutant in mutants/ through the grader and records the T1 (visible
tests), T2 (checkpoints) and T3 (hidden traces) scores, the first tier that
catches it, and the failure labels on its failing hidden seeds. This needs no
model calls: it measures how much of the bug space the visible tests in the
prompt miss, which is the mechanism behind hypothesis H1.

Usage: python tools/mutant_tier_analysis.py [--out results/grader_analysis]
"""
import argparse
import json
import sys
from collections import Counter
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

try:
    import tomllib as tomli
except ImportError:  # pragma: no cover
    import tomli  # type: ignore

from graders.dst_grader import grade_task  # noqa: E402


def _first_catching_tier(t1: float, t2: float, t3: float) -> str:
    if t1 < 1.0:
        return "T1"
    if t2 < 1.0:
        return "T2"
    if t3 < 1.0:
        return "T3"
    return "none"


def analyse() -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for task_dir in sorted((REPO_ROOT / "mutants").iterdir()):
        if not task_dir.is_dir():
            continue
        task_id = task_dir.name
        meta = tomli.loads((REPO_ROOT / "tasks" / task_id / "task.toml").read_text())
        for m_dir in sorted(d for d in task_dir.iterdir() if (d / "expect.toml").exists()):
            files = {}
            for rel in meta.get("target_files", []):
                f = m_dir / Path(rel).name
                if f.exists():
                    files[rel] = f.read_text(encoding="utf-8")
            rec = grade_task(task_id, files, is_candidate=True)
            labels: Counter[str] = Counter(
                lab for sf in (rec.seed_failures or []) for lab in sf["labels"]
            )
            rows.append({
                "task_id": task_id,
                "variant": meta.get("variant"),
                "mutant": m_dir.name,
                "t1": rec.t1,
                "t2": rec.t2,
                "t3": rec.t3,
                "score": rec.score,
                "caught_by": _first_catching_tier(rec.t1, rec.t2, rec.t3),
                "failing_seeds": len(rec.seed_failures or []),
                "seed_labels": dict(labels),
                "first_failure": (rec.first_failure or {}).get("invariant"),
                "error": rec.error,
            })
    return rows


def to_markdown(rows: list[dict[str, Any]]) -> str:
    n = len(rows)
    by_tier = Counter(r["caught_by"] for r in rows)
    pass_t1 = [r for r in rows if r["t1"] == 1.0]
    pass_t1_t2 = [r for r in rows if r["t1"] == 1.0 and r["t2"] == 1.0]
    hidden_first_d1_but_breach = [
        r for r in rows
        if r["first_failure"] == "D1"
        and set(r["seed_labels"]) & {"I1", "I1_ROLLBACK", "I2", "I3", "I4"}
    ]
    lines = [
        "# Mutant tier analysis",
        "",
        "Generated by `tools/mutant_tier_analysis.py` (no model calls). Each mutant is "
        "one realistic, hand-written bug in the target file.",
        "",
        f"- Mutants: **{n}**",
        f"- Pass every visible test in the prompt (T1 = 1.0): **{len(pass_t1)} / {n}**",
        f"- Pass visible tests *and* all targeted checkpoints (T1 = T2 = 1.0): "
        f"**{len(pass_t1_t2)} / {n}** — only the hidden simulation traces catch these",
        f"- First tier that catches the bug: T1 {by_tier['T1']}, T2 {by_tier['T2']}, "
        f"T3 {by_tier['T3']}, none {by_tier['none']}",
        f"- Mutants whose first reported failure is a report mismatch (D1) but which also "
        f"break a conservation invariant at that event: **{len(hidden_first_d1_but_breach)}**",
        "",
        "| Task | Mutant | T1 | T2 | T3 | Caught by | Failing seeds | Labels on failing seeds |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        labs = ", ".join(f"{k}×{v}" for k, v in sorted(r["seed_labels"].items())) or "–"
        lines.append(
            f"| `{r['task_id']}` | `{r['mutant']}` | {r['t1']:.2f} | {r['t2']:.2f} | "
            f"{r['t3']:.2f} | {r['caught_by']} | {r['failing_seeds']} / 20 | {labs} |"
        )
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description="Which grading tier catches each mutant.")
    ap.add_argument("--out", default=str(REPO_ROOT / "results" / "grader_analysis"))
    args = ap.parse_args()
    rows = analyse()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "mutant_tiers.json").write_text(json.dumps(rows, indent=2), encoding="utf-8")
    md = to_markdown(rows)
    (out / "mutant_tiers.md").write_text(md, encoding="utf-8")
    print(md)


if __name__ == "__main__":
    main()
